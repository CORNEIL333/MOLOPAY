export const ERROR_CODES = {
  INVALID_AMOUNT: 'INVALID_AMOUNT',
  CURRENCY_MISMATCH: 'CURRENCY_MISMATCH',
  ACCOUNT_NOT_FOUND: 'ACCOUNT_NOT_FOUND',
  LEDGER_INVALID_DRAFT: 'LEDGER_INVALID_DRAFT',
  LEDGER_UNBALANCED: 'LEDGER_UNBALANCED',
  LEDGER_APPEND_ONLY: 'LEDGER_APPEND_ONLY',
  LEDGER_SEQUENCE_GAP: 'LEDGER_SEQUENCE_GAP',
  LEDGER_REVERSAL_INVALID: 'LEDGER_REVERSAL_INVALID',
  IDEMPOTENCY_KEY_REUSED: 'IDEMPOTENCY_KEY_REUSED',
  PAYMENT_ALREADY_CONFIRMED: 'PAYMENT_ALREADY_CONFIRMED',
  UNAUTHORIZED_TRANSITION: 'UNAUTHORIZED_TRANSITION',
  MAKER_CANNOT_APPROVE: 'MAKER_CANNOT_APPROVE',
  PERMISSION_DENIED: 'PERMISSION_DENIED',
  AUDIT_INVALID_EVENT: 'AUDIT_INVALID_EVENT',
  AUDIT_CHAIN_BROKEN: 'AUDIT_CHAIN_BROKEN',
  AUDIT_SEQUENCE_GAP: 'AUDIT_SEQUENCE_GAP',
  AUDIT_APPEND_ONLY: 'AUDIT_APPEND_ONLY',
  AUDIT_REASON_REQUIRED: 'AUDIT_REASON_REQUIRED',
  AUDIT_SENSITIVE_METADATA: 'AUDIT_SENSITIVE_METADATA',
} as const;

export type ErrorCode = keyof typeof ERROR_CODES;

export class BusinessError extends Error {
  public readonly code: ErrorCode;

  public constructor(code: ErrorCode, message?: string) {
    super(message ?? code);
    this.name = 'BusinessError';
    this.code = code;
  }
}
